class Command(BaseCommand):
    help = 'Seed the food establishment evaluation items from the approved corrective-actions sheet'

    def handle(self, *args, **options):
        expected_numbers = []
        section_order = {}

        for number, section_title, text, corrective_action, priority in ITEMS:
            if section_title not in section_order:
                section_order[section_title] = len(section_order) + 1

            section, _ = Section.objects.update_or_create(
                title=section_title,
                defaults={'order': section_order[section_title]},
            )

            expected_numbers.append(number)
            Item.objects.update_or_create(
                number=number,
                defaults={
                    'section': section,
                    'text': text,
                    'corrective_action': corrective_action,
                    'priority': priority,
                },
            )

        Item.objects.exclude(number__in=expected_numbers).delete()
        Section.objects.exclude(title__in=section_order.keys()).delete()

        self.stdout.write(self.style.SUCCESS(f'Seeded {len(expected_numbers)} inspection items from corrective-actions sheet.'))
